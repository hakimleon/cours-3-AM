/**
 * Retourne l'activité de découverte d'un cours (ou en génère une automatiquement
 * selon le gabarit fixe en 3 temps pour tout futur cours ajouté au moteur).
 */
export function getCourseDiscoveryActivity(course: Course): DiscoveryActivity {
  if (course.discoveryActivity) {
    return course.discoveryActivity;
  }

  const mapped = DISCOVERY_ACTIVITIES_BY_COURSE[course.id];
  if (mapped) {
    return mapped;
  }

  // Génération automatique conforme au gabarit en 3 temps pour tout nouveau cours (22..42)
  const firstExample = course.guidedExamples?.[0];
  const sampleInput = firstExample?.initialMath || course.primaryFormula.math;
  const sampleResult =
    firstExample?.conclusion ||
    firstExample?.steps?.[firstExample.steps.length - 1]?.math?.[0] ||
    course.primaryFormula.math;

  return {
    situation: `نعتبر الوضعية العددية والهندسية المبسطة الآتية لدراسة العلاقة بين المعطيات والنتيجة قبل صياغة القاعدة العامة :`,
    dataTable: {
      headers: ['المعطيات الأولية', 'الخطوة الحسابية المرحلية', 'النتيجة الملاحظة'],
      rows: [
        [
          sampleInput,
          firstExample?.steps?.[0]?.math?.[0] || 'حساب مباشر للمقدار الأول',
          sampleResult,
        ],
      ],
    },
    questions: [
      'احسب المقدار المرحلي في الجدول وتحقق من النتيجة المسجلة في العمود الأخير.',
      'ماذا تلاحظ حول العلاقة الثابتة التي تربط بين المعطيات والنتيجة في هذه الوضعية؟',
    ],
    hint: course.primaryFormula.condition || 'استعمل العمليات الأساسية المألوفة لمقارنة الطرفين.',
    correction: {
      questionAnswers: [
        `بتطبيق الحساب المرحلي نجد النتيجة المطابقة: ${sampleResult}.`,
        `نستنتج العلاقة العامة المتمثلة في: ${course.primaryFormula.note || course.heroDescription}`,
      ],
    },
  };
}

